/** The trailing timing block, shared by the cadence rows and the final row. */
const timingCells = (timing: SnapshotTiming): string[] => [
  String(timing.ticks),
  timing.tickMeanMs.toFixed(4),
  timing.tickMaxMs.toFixed(4),
  String(timing.decisions),
  timing.decisionMeanMs.toFixed(4),
  timing.decisionMaxMs.toFixed(4),
];

/**
 * `sell@6` — the direction and the slider stop, or `off`. One stop is 1e-9 of the
 * reserve up to all of it, so the stop is the honest way to read an intensity.
 */
const routeCell = (
  state: CivilizationState,
  resource: TradeResourceKey,
): string => {
  const route = state.getTradeRoute(resource);
  return route.enabled
    ? `${route.mode}@${tradeIntensityStop(route.intensity)}`
    : "off";
};

const row = (
  state: CivilizationState,
  t: number,
  timing: SnapshotTiming,
  index: number,
): string[] => {
  const cells: string[] = [
    String(t),
    clock(t),
    state.getCurrentAge()?.key ?? "",
    state.population.toString(),
    state.resources.peopleCapacity.toString(),
    String(
      Object.values(state.builtBuildings).reduce(
        (sum, count) => sum + (count ?? 0),
        0,
      ),
    ),
    String(state.defeatedEncounters.length),
    state.resources.trade.toString(),
    state.getTradePowerRate().toString(),
    String(state.getActiveTradeRoutes().length),
    ...tradeableResourceKeys.map((resource) => routeCell(state, resource)),
  ];

  for (const building of WORKER_BUILDINGS) {
    const key = building.key as BuildingKey;
    cells.push(
      String(state.getBuildingCount(key)),
      workerCell(state, key),
      rateCell(state, key),
    );
  }

  cells.push(
    String(state.boughtResearch.length),
    costCell(state.getResearchNextCost()),
    factor(state.getResearchNextCost()[0]?.factor ?? 0),
    state.getArmyPower().toString(),
  );

  for (const building of buildingDefinitions) {
    const key = building.key as BuildingKey;
    const count = state.getBuildingCount(key);
    const parameters = state.getBuildingCostParameters(key);
    cells.push(
      state.isBuildingAvailable(key)
        ? costCell(state.getBuildingCost(key, count, 1))
        : "",
      bonusCell(state, key, count),
      factor(parameters[0]?.reductions.base ?? 0),
      factor(parameters[0]?.reductions.factor ?? 0),
      factor(parameters[0]?.reductions.percent ?? 0),
      factor(parameters[0]?.reductions.flat ?? 0),
      parameters.map((p) => factor(p.unitFactor)).join("|"),
    );
  }

  for (const unit of UNITS) {
    const owned = state.getUnitCount(unit.key);
    const available = state.isUnitAvailable(unit.key);
    const stats = available ? state.getUnitStats(unit.key) : undefined;
    cells.push(
      owned.sign > 0 ? owned.toString() : "0",
      // Blank while the unit is locked, exactly as asked.
      available ? costCell(state.getUnitCost(unit.key, 1)) : "",
      stats ? factor(unitPower(stats)) : "",
    );
  }

  for (const resource of producerResourceKeys) {
    cells.push(
      (state.statistics.resourcesSpent[resource] ?? ExpNumber.ZERO).toString(),
    );
  }

  cells.push(
    state.earnedAchievements.join("|"),
    state.boughtUpgrades.join("|"),
    state.boughtResearch.join("|"),
  );
  cells.push(String(index), ...timingCells(timing));
  return cells;
};

/** CSV escaping: quote when the cell contains a comma, quote or newline. */
const csvCell = (value: string): string =>
  /[",\n]/.test(value) ? `"${value.replaceAll('"', '""')}"` : value;
const csvLine = (cells: string[]): string => cells.map(csvCell).join(",");

type Sheet = { name: string; header: string; rows: string[] };

/**
 * Upgrades whose purchase is timed like a battle. `wonder0` (the Great Monument)
 * is what closes an age in practice, so its timestamp is the end-of-age event —
 * add to this list rather than special-casing an id inline.
 */
const MILESTONE_UPGRADES = ["wonder0"];

/* ---------------------------------------------------- run one strategy */

/** Runs a strategy and returns one CSV line per `interval` simulated seconds. */
const runStrategy = (
  name: string,
  onRow: (line: string) => void,
  onMilestone: (line: string) => void,
): {
  sheet: Sheet;
  wall: number;
  gameTime: number;
  arrived: boolean;
  milestones: Milestone[];
} | null => {
  const strategy = getStrategy(name);
  if (!strategy) return null;
  const started = Date.now();

  /**
   * Milestones are recorded off the strategy hook rather than the CSV rows, so
   * they resolve to the exact second an event happened rather than being snapped
   * to the next `interval` boundary. A single arrival time hides where a run
   * actually spends its budget — a strategy can be behind on barracks and still
   * finish first, or win early and then stall on buildings.
   */
  const milestones: Milestone[] = [];
  const mark = (label: string, at: number) => {
    if (!milestones.some((m) => m.label === label)) {
      milestones.push({ label, at });
      onMilestone(`${name}  ${label.padEnd(24)} ${clock(at).padStart(9)}`);
    }
  };
  const notedBattles = new Set<string>();
  const notedResearch = new Set<number>();
  const notedFirstResearch = new Set<number>();
  const notedUpgrades = new Set<string>();

  // The capture rides on the strategy hook, so it sees exactly the state the
  // runner would have snapshotted at that second. `rowIndex` is a local counter
  // rather than `rows.length`, so the emitted index stays contiguous even if a
  // row is ever dropped.
  const rows: string[] = [];
  let nextAt = 0;
  let rowIndex = 0;
  const capture = {
    name: strategy.name,
    description: strategy.description,
    decideAction: (
      state: CivilizationState,
      context: { gameTime: number; snapshots: never[]; timing: SnapshotTiming },
    ) => {
      const at = context.gameTime;
      // Population gates, in the order the game presents them.
      for (const gate of [90, 200, 500, 1000, 5000, 10000]) {
        if (state.population.gte(ExpNumber.fromNumber(gate))) {
          mark(gate === 90 ? "90 pop (barracks)" : `${gate} pop`, at);
        }
      }
      // Every battle won, in encounter order rather than the order they happen.
      for (const id of state.defeatedEncounters) {
        if (!notedBattles.has(id)) {
          notedBattles.add(id);
          mark(`won ${id.replace(/^age\d_/, "")}`, at);
        }
      }
      // Structural upgrades, timed the same way so an end-of-age event can be
      // compared against the battles and research around it.
      for (const id of MILESTONE_UPGRADES) {
        if (state.isUpgradeBought(id) && !notedUpgrades.has(id)) {
          notedUpgrades.add(id);
          mark(`built ${id}`, at);
        }
      }
      // Research completion is per age and only exists while a tech is buyable;
      // a run that never finishes an age simply records nothing for it.
      const age = state.getCurrentAge();
      const ageIndex = age
        ? ageDefinitions.findIndex((a) => a.key === age.key)
        : -1;
      if (ageIndex >= 0) {
        const ageTechs = researchDefinitions.filter(
          (r) => r.age === ageIndex,
        );
        // The first tech bought in this age. Paired with "<age> research done"
        // below — the last — so the pair brackets how long research in an age
        // actually took, which a single arrival time cannot show.
        if (
          !notedFirstResearch.has(ageIndex) &&
          ageTechs.some((r) => state.isResearchBought(r.key))
        ) {
          notedFirstResearch.add(ageIndex);
          mark(`first ${age?.name ?? ageIndex} research`, at);
        }
        const finished =
          ageTechs.length > 0 &&
          ageTechs.every(
            (r) => !state.isResearchUnlocked(r.key) || state.isResearchBought(r.key),
          );
        if (finished && !notedResearch.has(ageIndex)) {
          notedResearch.add(ageIndex);
          mark(`${age?.name ?? ageIndex} research done`, at);
        }
      }
      // Age entry, so "reached age1" and "how the run went getting there" sit
      // on the same report.
      if (age) mark(`entered ${age.key}`, at);

      if (at >= nextAt) {
        const line = csvLine(row(state, at, context.timing, rowIndex));
        rows.push(line);
        onRow(line);
        rowIndex += 1;
        nextAt = at + interval;
      }
      return strategy.decideAction(state, {
        gameTime: at,
        snapshots: context.snapshots,
        timing: context.timing,
      });
    },
  };

  const result = new GameSimulation(
    saveEntry ? loadSaveEntry(saveEntry.path).state : createInitialState(),
    capture,
    {
      // An age target ends the run at the transition; the horizon still caps it,
      // so "never got there" reports as a full-length run rather than vanishing.
      objective: targetAge
        ? { type: "ageReach", ageId: targetAge }
        : { type: "timeLimit", seconds: horizon },
      gatherClicksPerAction: 10,
      maxGameTime: horizon,
      recordSnapshots: true,
      snapshotIntervalSeconds: interval,
      // A save is a mid-game state: the from-scratch prologue must not run.
      fromScratch: saveEntry === null,
    },
  ).run();

  // The closing row reads the run's own final accumulators, so it reports the
  // whole-run mean rather than the cadence sample that preceded it.
  const finalTiming: SnapshotTiming = {
    ticks: result.tickTiming.ticks,
    tickMeanMs: result.tickTiming.meanMs,
    tickMaxMs: result.tickTiming.maxMs,
    decisions: result.decisionTiming.decisions,
    decisionMeanMs: result.decisionTiming.meanMs,
    decisionMaxMs: result.decisionTiming.maxMs,
  };
  const finalRow = row(
    result.finalState,
    result.gameTime,
    finalTiming,
    rowIndex,
  );
  if (rows.length === 0 || rows[rows.length - 1][0] !== finalRow[0]) {
    const line = csvLine(finalRow);
    rows.push(line);
    onRow(line);
  }
  return {
    sheet: { name, header: csvLine(header), rows },
    wall: Math.round((Date.now() - started) / 1000),
    gameTime: result.gameTime,
    // "Objective reached" is a real arrival; anything else under an age target
    // means the run hit the horizon first, which the reader must be able to see.
    arrived: !targetAge || result.terminationReason === "Objective reached",
    milestones,
  };
};

/* ------------------------------------------------- minimal ODS (zip) writer */

const crcTable = (() => {
  const table = new Int32Array(256);
  for (let i = 0; i < 256; i += 1) {
    let c = i;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[i] = c;
  }
  return table;
})();

const crc32 = (buf: Buffer): number => {
  let c = 0xffffffff;
  for (const byte of buf) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};

/** Build a ZIP container from named string entries (deflate, or stored). */
const zip = (
  entries: { name: string; data: Buffer; store?: boolean }[],
): Buffer => {
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  for (const entry of entries) {
    const nameBytes = Buffer.from(entry.name, "utf8");
    const raw = entry.data;
    const deflated = entry.store ? raw : deflateRawSync(raw);
    const method = entry.store ? 0 : 8;
    const crc = crc32(raw);

    const local = Buffer.alloc(30 + nameBytes.length);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(method, 8);
    local.writeUInt16LE(0, 10);
    local.writeUInt16LE(0, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(deflated.length, 18);
    local.writeUInt32LE(raw.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    local.writeUInt16LE(0, 28);
    nameBytes.copy(local, 30);

    const central = Buffer.alloc(46 + nameBytes.length);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0, 8);
    central.writeUInt16LE(method, 10);
    central.writeUInt16LE(0, 12);
    central.writeUInt16LE(0, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(deflated.length, 20);
    central.writeUInt32LE(raw.length, 24);
    central.writeUInt16LE(nameBytes.length, 28);
    central.writeUInt16LE(0, 30);
    central.writeUInt16LE(0, 32);
    central.writeUInt16LE(0, 34);
    central.writeUInt16LE(0, 36);
    central.writeUInt32LE(0, 38);
    central.writeUInt32LE(offset, 42);
    nameBytes.copy(central, 46);

    locals.push(local, deflated);
    centrals.push(central);
    offset += local.length + deflated.length;
  }
  const centralBuf = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(0, 4);
  end.writeUInt16LE(0, 6);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(centralBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  end.writeUInt16LE(0, 20);
  return Buffer.concat([...locals, centralBuf, end]);
};

const xml = (value: string): string =>
  value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

const writeWorkbook = (sheets: Sheet[], columns: number): void => {
  if (sheets.length === 0) return;
  const ods = zip([
    {
      name: "mimetype",
      data: Buffer.from(
        "application/vnd.oasis.opendocument.spreadsheet",
        "utf8",
      ),
      store: true,
    },
    {
      name: "META-INF/manifest.xml",
      data: Buffer.from(manifest(sheets), "utf8"),
    },
    { name: "content.xml", data: Buffer.from(odsContent(sheets), "utf8") },
    ...sheets.map((sheet, i) => ({
      name: `sim-${i + 1}.csv`,
      data: Buffer.from(
        [sheet.header, ...sheet.rows].join("\n") + "\n",
        "utf8",
      ),
    })),
  ]);
  const file = `${outDir}/simulations.ods`;
  writeFileSync(file, ods);
  console.log(
    `\nworkbook: ${file}  (${sheets.length} sheets: ${sheets.map((s) => s.name).join(", ")})`,
  );
  console.log(`columns per sheet: ${columns}`);
};

/** One ODS sheet per simulation. Values are written as strings, which is what a
 *  balance sheet wants anyway: ExpNumber strings and `a|b` lists stay readable. */
const odsContent = (sheets: Sheet[]): string => {
  const body = sheets
    .map((sheet) => {
      const rows = [sheet.header, ...sheet.rows]
        .map(
          (line) =>
            `<table:table-row>${line
              .split(",")
              .map((cell) => {
                // A quoted CSV cell is already escaped; keep the quotes literal.
                const value = cell.startsWith('"')
                  ? cell.slice(1, -1).replaceAll('""', '"')
                  : cell;
                return `<table:table-cell office:value-type="string"><text:p>${xml(value)}</text:p></table:table-cell>`;
              })
              .join("")}</table:table-row>`,
        )
        .join("");
      return `<table:table table:name="${xml(sheet.name)}">${rows}</table:table>`;
    })
    .join("");
  return `<?xml version="1.0" encoding="UTF-8"?>
<office:document-content
  xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0"
  xmlns:table="urn:oasis:names:tc:opendocument:xmlns:table:1.0"
  xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0">
<office:body><office:spreadsheet>${body}</office:spreadsheet></office:body>
</office:document-content>`;
};

const manifest = (
  sheets: Sheet[],
): string => `<?xml version="1.0" encoding="UTF-8"?>
<manifest:manifest xmlns:manifest="urn:oasis:names:tc:opendocument:xmlns:manifest:1.0" manifest:version="1.2">
<manifest:file-entry manifest:full-path="/" manifest:media-type="application/vnd.oasis.opendocument.spreadsheet"/>
<manifest:file-entry manifest:full-path="content.xml" manifest:media-type="text/xml"/>
${sheets
  .map(
    (_, i) =>
      `<manifest:file-entry manifest:full-path="sim-${i + 1}.csv" manifest:media-type="text/csv"/>`,
  )
  .join("")}
</manifest:manifest>`;

